'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('pv', {
  state: () => ipcRenderer.invoke('state'),
  activity: () => ipcRenderer.invoke('activity'),
  pathForFile: (file) => webUtils.getPathForFile(file),
  pickVault: () => ipcRenderer.invoke('vault:pick'),
  chooseVault: (file) => ipcRenderer.invoke('vault:choose', file),
  pickKeyFile: () => ipcRenderer.invoke('keyfile:pick'),
  createKeyFile: () => ipcRenderer.invoke('keyfile:create'),
  create: (opts) => ipcRenderer.invoke('vault:create', opts),
  unlock: (opts) => ipcRenderer.invoke('vault:unlock', opts),
  lock: () => ipcRenderer.invoke('vault:lock'),
  forget: () => ipcRenderer.invoke('vault:forget'),
  changeMaster: (opts) => ipcRenderer.invoke('vault:change-master', opts),
  revealVault: () => ipcRenderer.invoke('vault:reveal'),
  list: (q) => ipcRenderer.invoke('entries:list', q),
  get: (id) => ipcRenderer.invoke('entry:get', id),
  save: (input) => ipcRenderer.invoke('entry:save', input),
  favorite: (id, on) => ipcRenderer.invoke('entry:favorite', id, on),
  trash: (id) => ipcRenderer.invoke('entry:trash', id),
  restore: (id) => ipcRenderer.invoke('entry:restore', id),
  purge: (id) => ipcRenderer.invoke('entry:purge', id),
  emptyTrash: () => ipcRenderer.invoke('trash:empty'),
  addFolder: (name) => ipcRenderer.invoke('folder:add', name),
  setSettings: (s) => ipcRenderer.invoke('settings:set', s),
  reveal: (id, what, index) => ipcRenderer.invoke('secret:reveal', id, what, index),
  copy: (id, what, index) => ipcRenderer.invoke('secret:copy', id, what, index),
  copyText: (text) => ipcRenderer.invoke('clipboard:copy-text', text),
  totp: (id) => ipcRenderer.invoke('totp:now', id),
  genPassword: (o) => ipcRenderer.invoke('gen:password', o),
  genPassphrase: (o) => ipcRenderer.invoke('gen:passphrase', o),
  strength: (pw, inputs) => ipcRenderer.invoke('strength', pw, inputs),
  importPick: () => ipcRenderer.invoke('import:pick'),
  importCommit: () => ipcRenderer.invoke('import:commit'),
  importCancel: () => ipcRenderer.invoke('import:cancel'),
  exportCsv: () => ipcRenderer.invoke('export:csv'),
  exportBackup: () => ipcRenderer.invoke('export:backup'),
  showFile: (file) => ipcRenderer.invoke('reveal', file),
  onLocked: (cb) => ipcRenderer.on('vault:locked', (_e, s) => cb(s)),
  onConflict: (cb) => ipcRenderer.on('vault:conflict', (_e, s) => cb(s)),
  onClipboardCleared: (cb) => ipcRenderer.on('clipboard:cleared', () => cb()),
});
